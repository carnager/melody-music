"""Writes docs/adr/README.md, the index of every ADR, from the ADRs themselves.

Run it after adding an ADR or changing one's status:

    python3 scripts/adr_index.py

Each row is an ADR's number, title and the first sentence of its status. "Changed
by" lists later ADRs whose own status says they supersede, replace, retire,
amend, revise or change it -- so a reader of an old decision finds the newer
one without every old ADR having been edited.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ADR = ROOT / "docs" / "adr"
CHANGING = re.compile(r"supersed|replac|retire|amend|revis|chang", re.IGNORECASE)


def status_of(text):
    """The status text, from a `Status:` line or a `## Status` section."""
    line = re.search(r"^(?:- )?Status:\s*(.*(?:\n(?![-#\n]).*)*)", text, re.MULTILINE)
    section = re.search(r"^## Status\s*\n\s*\n?((?:.+\n?)+)", text, re.MULTILINE)
    found = line or section
    return " ".join(found.group(1).split()) if found else ""


def first_sentence(status):
    sentence = re.split(r"(?<=[.;])\s", status, maxsplit=1)[0]
    return sentence.rstrip(".;")


def main():
    adrs = []
    for path in sorted(ADR.glob("[0-9][0-9][0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        title = re.search(r"^# (.*)$", text, re.MULTILINE).group(1)
        title = re.sub(r"^ADR-\d{4}:\s*", "", re.sub(r"^ADR-\d{4} addendum:\s*", "Addendum: ", title))
        adrs.append((path.name[:4], path.name, title, status_of(text)))
    changed_by = {}
    for number, _, _, status in adrs:
        if not CHANGING.search(status):
            continue
        for earlier in re.findall(r"ADR-(\d{4})", status):
            if earlier < number:
                changed_by.setdefault(earlier, set()).add(number)
    lines = [
        "# Architecture decision records",
        "",
        "Generated by `scripts/adr_index.py` from the ADRs; run it again after",
        "adding one or changing a status. Newest first. A decision's status says",
        "whether it still holds; **Changed by** names later decisions that say",
        "they supersede, replace, retire or amend it.",
        "",
        "| ADR | Decision | Status | Changed by |",
        "| --- | --- | --- | --- |",
    ]
    for number, name, title, status in reversed(adrs):
        later = ", ".join(
            f"[{n}]({next(a[1] for a in adrs if a[0] == n)})"
            for n in sorted(changed_by.get(number, ()))
        )
        cell = first_sentence(status).replace("|", "\\|")
        lines.append(f"| {number} | [{title.replace('|', '\\|')}]({name}) | {cell} | {later} |")
    output = ADR / "README.md"
    content = "\n".join(lines) + "\n"
    if "--check" in sys.argv[1:]:
        if output.read_text(encoding="utf-8") != content:
            sys.exit("docs/adr/README.md is out of date: run python3 scripts/adr_index.py")
        return
    output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
